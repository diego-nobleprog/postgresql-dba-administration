-- Crear el schema comercial con propietario independiente.
CREATE SCHEMA comercial AUTHORIZATION p8_owner;

-- Crear el schema de reportes comerciales.
CREATE SCHEMA reportes AUTHORIZATION p8_owner;

-- Crear el schema de auditoria.
CREATE SCHEMA auditoria AUTHORIZATION p8_owner;

-- Ejecutar los objetos siguientes como su propietario.
SET ROLE p8_owner;

-- Crear la tabla de clientes.
CREATE TABLE comercial.clientes (cliente_id integer PRIMARY KEY, nombre varchar(100) NOT NULL, ciudad varchar(80) NOT NULL);

-- Crear la tabla de productos con restriccion de precio.
CREATE TABLE comercial.productos (producto_id integer PRIMARY KEY, nombre varchar(100) NOT NULL, precio numeric(12,2) NOT NULL CHECK (precio > 0));

-- Crear la tabla de pedidos con identidad automatica.
CREATE TABLE comercial.pedidos (pedido_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 5003) PRIMARY KEY, cliente_id integer NOT NULL REFERENCES comercial.clientes(cliente_id), total numeric(12,2) NOT NULL CHECK (total > 0), estado varchar(20) NOT NULL CHECK (estado IN ('PENDIENTE','PAGADO','CANCELADO')), fecha timestamptz NOT NULL DEFAULT now());

-- Crear el detalle y sus relaciones con pedidos y productos.
CREATE TABLE comercial.detalles (pedido_id bigint NOT NULL REFERENCES comercial.pedidos(pedido_id), producto_id integer NOT NULL REFERENCES comercial.productos(producto_id), cantidad integer NOT NULL CHECK (cantidad > 0), subtotal numeric(12,2) NOT NULL CHECK (subtotal > 0), PRIMARY KEY (pedido_id,producto_id));

-- Crear la secuencia explicita de pagos.
CREATE SEQUENCE comercial.pagos_seq START WITH 9002;

-- Crear la tabla de pagos que utiliza la secuencia.
CREATE TABLE comercial.pagos (pago_id bigint PRIMARY KEY DEFAULT nextval('comercial.pagos_seq'::regclass), pedido_id bigint NOT NULL REFERENCES comercial.pedidos(pedido_id), monto numeric(12,2) NOT NULL CHECK (monto > 0), fecha timestamptz NOT NULL DEFAULT now());

-- Crear la tabla de auditoria de cambios.
CREATE TABLE auditoria.cambios_pedidos (auditoria_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pedido_id bigint NOT NULL, estado_anterior varchar(20), estado_nuevo varchar(20), fecha timestamptz NOT NULL DEFAULT now());

-- Crear un indice B-tree almacenado en el tablespace alternativo.
CREATE INDEX idx_pedidos_estado ON comercial.pedidos (estado) TABLESPACE p8_ts_indices;

-- Crear un indice GIN utilizando la extension pg_trgm.
CREATE INDEX idx_productos_nombre_trgm ON comercial.productos USING gin (nombre gin_trgm_ops);

-- Crear una funcion de consulta del total de pedidos.
CREATE FUNCTION comercial.total_pedido(p_pedido_id bigint) RETURNS numeric LANGUAGE sql STABLE AS 'SELECT total FROM comercial.pedidos WHERE pedido_id = $1';

-- Crear una funcion de auditoria que se ejecuta mediante trigger.
CREATE FUNCTION auditoria.registrar_cambio_pedido() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, comercial, auditoria AS $$
-- Iniciar el procesamiento de auditoria.
BEGIN
    -- Identificar cambios efectivos en el estado.
    IF NEW.estado IS DISTINCT FROM OLD.estado THEN
        -- Registrar los estados anterior y nuevo.
        INSERT INTO auditoria.cambios_pedidos (pedido_id, estado_anterior, estado_nuevo) VALUES (NEW.pedido_id, OLD.estado, NEW.estado);
    -- Finalizar la comparacion del estado.
    END IF;
    -- Conservar la fila modificada.
    RETURN NEW;
-- Finalizar la funcion de auditoria.
END;
-- Cerrar el cuerpo de la funcion.
$$;

-- Crear un trigger de cambios de estado.
CREATE TRIGGER trg_pedido_estado AFTER UPDATE OF estado ON comercial.pedidos FOR EACH ROW EXECUTE FUNCTION auditoria.registrar_cambio_pedido();

-- Crear el procedimiento de registro de pagos.
CREATE PROCEDURE comercial.registrar_pago(p_pedido_id bigint, p_monto numeric) LANGUAGE plpgsql AS $$
-- Declarar el total del pedido.
DECLARE v_total numeric;
        -- Declarar el estado actual del pedido.
        v_estado varchar(20);
-- Iniciar el procedimiento.
BEGIN
    -- Bloquear el pedido y consultar su estado.
    SELECT total, estado INTO v_total, v_estado FROM comercial.pedidos WHERE pedido_id=p_pedido_id FOR UPDATE;
    -- Identificar pedidos inexistentes.
    IF NOT FOUND THEN
        -- Lanzar un error de pedido inexistente.
        RAISE EXCEPTION 'Pedido inexistente: %', p_pedido_id;
    -- Finalizar la comprobacion de existencia.
    END IF;
    -- Validar el estado y monto del pago.
    IF v_estado <> 'PENDIENTE' OR p_monto <> v_total THEN
        -- Rechazar pagos que no cumplen las reglas.
        RAISE EXCEPTION 'Pago invalido para pedido %', p_pedido_id;
    -- Finalizar la validacion del pago.
    END IF;
    -- Registrar el pago del pedido.
    INSERT INTO comercial.pagos (pedido_id,monto) VALUES (p_pedido_id,p_monto);
    -- Marcar el pedido como pagado.
    UPDATE comercial.pedidos SET estado='PAGADO' WHERE pedido_id=p_pedido_id;
-- Finalizar el procedimiento.
END;
-- Cerrar el cuerpo del procedimiento.
$$;

-- Crear una vista de ventas pagadas por cliente.
CREATE VIEW reportes.v_ventas_pagadas AS SELECT c.cliente_id,c.nombre,COALESCE(SUM(pg.monto),0)::numeric(12,2) AS total_pagado FROM comercial.clientes c LEFT JOIN comercial.pedidos p ON p.cliente_id=c.cliente_id LEFT JOIN comercial.pagos pg ON pg.pedido_id=p.pedido_id GROUP BY c.cliente_id,c.nombre;

-- Crear una vista materializada inicialmente sin datos.
CREATE MATERIALIZED VIEW reportes.mv_ventas_pagadas AS SELECT * FROM reportes.v_ventas_pagadas WITH NO DATA;

-- Regresar al rol administrador.
RESET ROLE;

