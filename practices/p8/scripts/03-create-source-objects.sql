GRANT SELECT ON ALL TABLES IN SCHEMA comercial TO p8_reader,p8_reporter;

-- Permitir lectura comercial a la aplicacion.
GRANT SELECT ON ALL TABLES IN SCHEMA comercial TO p8_app;

-- Permitir registrar y modificar pedidos.
GRANT INSERT,UPDATE ON comercial.pedidos TO p8_app;

-- Permitir insertar pagos.
GRANT INSERT ON comercial.pagos TO p8_app;

-- Permitir utilizar secuencias comerciales.
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA comercial TO p8_app;

