GRANT SELECT ON ALL TABLES IN SCHEMA reportes TO p8_reader,p8_reporter;

-- Permitir ejecutar la funcion de consulta.
GRANT EXECUTE ON FUNCTION comercial.total_pedido(bigint) TO p8_app;

-- Permitir ejecutar el procedimiento de pago.
GRANT EXECUTE ON PROCEDURE comercial.registrar_pago(bigint,numeric) TO p8_app;
